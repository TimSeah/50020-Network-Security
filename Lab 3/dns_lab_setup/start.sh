#!/usr/bin/env bash
set -Eeuo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"
REBUILD=0
if [[ "${1:-}" == "--rebuild" ]]; then
    REBUILD=1
elif [[ $# -gt 0 ]]; then
    echo "Usage: ./start.sh [--rebuild]" >&2
    exit 2
fi

if docker info >/dev/null 2>&1; then
    DOCKER=(docker)
elif command -v sudo >/dev/null 2>&1 && sudo docker info >/dev/null 2>&1; then
    DOCKER=(sudo docker)
else
    echo "Docker is not running or is not accessible." >&2
    exit 1
fi

if "${DOCKER[@]}" compose version >/dev/null 2>&1; then
    COMPOSE=("${DOCKER[@]}" compose)
else
    echo "Docker Compose v2 ('docker compose') is required." >&2
    exit 1
fi

mkdir -p .runtime
DISPLAY_VALUE="${DISPLAY:-:0}"
LAB_XAUTH="$(pwd)/.runtime/Xauthority"
rm -f "$LAB_XAUTH"
touch "$LAB_XAUTH"
chmod 0600 "$LAB_XAUTH"
XAUTH_FILE="$LAB_XAUTH"

if command -v xauth >/dev/null 2>&1 && [[ -n "${DISPLAY:-}" ]] && [[ -d /tmp/.X11-unix ]]; then
    xauth nlist "$DISPLAY" 2>/dev/null | sed -e 's/^..../ffff/' | xauth -f "$LAB_XAUTH" nmerge - 2>/dev/null || true
elif [[ -n "${XAUTHORITY:-}" && -r "${XAUTHORITY:-}" ]]; then
    cp "${XAUTHORITY}" "$LAB_XAUTH"
elif [[ -r "${HOME:-/nonexistent}/.Xauthority" ]]; then
    cp "${HOME}/.Xauthority" "$LAB_XAUTH"
fi

cat > .env <<EOFENV
LAB_DISPLAY="$DISPLAY_VALUE"
LAB_XAUTHORITY="$XAUTH_FILE"
EOFENV

IMAGE='kali-dns-lab:2026.09-real-example'
if [[ "$REBUILD" -eq 1 ]]; then
    "${DOCKER[@]}" build --no-cache -t "$IMAGE" .
else
    "${DOCKER[@]}" build -t "$IMAGE" .
fi

"${COMPOSE[@]}" up -d --remove-orphans

wait_socket() {
    local container=$1 pattern=$2 label=$3
    local i
    for i in {1..60}; do
        if "${DOCKER[@]}" exec "$container" sh -c "ss -H -lntu 2>/dev/null | grep -Eq '$pattern'"; then
            return 0
        fi
        if ! "${DOCKER[@]}" inspect -f '{{.State.Running}}' "$container" 2>/dev/null | grep -qx true; then
            echo "$label failed: $container is not running." >&2
            "${DOCKER[@]}" logs --tail 80 "$container" >&2 || true
            return 1
        fi
        sleep 1
    done
    echo "Timed out waiting for $label." >&2
    "${DOCKER[@]}" logs --tail 80 "$container" >&2 || true
    return 1
}

wait_socket node2 '10\.11\.2\.6:53|127\.0\.0\.1:53' 'node2 BIND'
wait_socket node2 '127\.0\.0\.1:953' 'node2 RNDC control channel'
wait_socket node4 '10\.11\.2\.8:53|127\.0\.0\.1:53' 'node4 BIND'
wait_socket node4 '127\.0\.0\.1:953' 'node4 RNDC control channel'
wait_socket node4 '(^|[[:space:]])(0\.0\.0\.0|\*):80([[:space:]]|$)' 'node4 web server'
for c in node1 node2 node3 node4; do
    wait_socket "$c" '(^|[[:space:]])(0\.0\.0\.0|\*):22([[:space:]]|$)|\[::\]:22' "$c SSH"
done

INSTALL_TARGET=/usr/local/bin/docksh
install_docksh() {
    if [[ ! -f .runtime/docksh.installed && ( -e "$INSTALL_TARGET" || -L "$INSTALL_TARGET" ) ]]; then
        if [[ -w /usr/local/bin ]]; then
            cp -a "$INSTALL_TARGET" .runtime/docksh.backup
        elif command -v sudo >/dev/null 2>&1; then
            sudo cp -a "$INSTALL_TARGET" .runtime/docksh.backup
        else
            return 1
        fi
    fi

    if [[ -w /usr/local/bin ]]; then
        install -m 0755 ./docksh "$INSTALL_TARGET"
    elif command -v sudo >/dev/null 2>&1; then
        sudo install -m 0755 ./docksh "$INSTALL_TARGET"
    else
        return 1
    fi
    touch .runtime/docksh.installed
}

if ! install_docksh; then
    echo "Could not install $INSTALL_TARGET; use ./docksh from this directory." >&2
fi

cat <<'EOFMSG'
DNS lab started successfully.

  node1  user       10.11.2.5  -> DNS 10.11.2.6
  node2  localdns   10.11.2.6  recursive/caching BIND (iterative Internet DNS)
  node3  analyst    10.11.2.7  -> DNS 10.11.2.6
  node4  attackerns 10.11.2.8  authoritative DNS + web

Lab authoritative zones on node4:
  attackerpage.com -> 10.11.2.8 (node2 forwards only this lab zone)
  example.com      -> 10.11.2.8 (DIRECT queries to node4 only)

Normal example.com queries through node2 use the real public DNS hierarchy.
All other public zones also use true root/TLD/authoritative recursion.
No external DNS query is generated by start.sh itself.

Open a shell with: docksh node1   (or node2/node3/node4)
Run ./check.sh for local lab verification.
Run ./check.sh --internet to verify direct Internet recursion.
EOFMSG
